"""Generate docs/assurance/design-trace.md: each D-ID and the src/ files that cite it
(R25 F3, NPR 7150.2D SWE-052 design -> code). Run: uv run python -m scripts.design_trace"""

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs/assurance/design-trace.md"
D_ID = re.compile(r"\bD-[A-Z]+-\d+\b")
HEADER = """# Design to code index

Generated by `scripts/design_trace.py` from the D-ID mentions in `src/` only (not `ui/`, `tests/`,
`e2e/`: a decision built in the console or only tested shows as uncited). Do not edit by hand: run
`uv run python -m scripts.design_trace`. Meta test `tests/meta/test_design_trace.py` fails when this
file is stale or when `src/` cites a D-ID that `docs/design.md` does not define. The other direction
(requirement to decision to test) is `docs/requirements.md`.

| Decision | Files that cite it |
| --- | --- |
"""
UNCITED = """
## Decisions with no citation in `src/`

Informative, not an error: defined in `docs/design.md`, cited nowhere in `src/`. Many are UI,
test, perf or process decisions (built outside `src/`); a few are designed and not built. Check
before reading a gap into it.

"""


def cited(src: Path) -> dict[str, list[str]]:
    found: dict[str, set[str]] = {}
    for f in src.rglob("*.py"):
        for d in D_ID.findall(f.read_text(encoding="utf-8")):
            found.setdefault(d, set()).add(f.relative_to(src).as_posix())
    return {d: sorted(found[d]) for d in sorted(found)}


def defined(design: Path) -> set[str]:
    return set(re.findall(r"^\| (D-[A-Z]+-\d+) ", design.read_text(encoding="utf-8"), re.M))


def uncited(src: Path, design: Path) -> list[str]:
    return sorted(defined(design) - set(cited(src)))


def render(src: Path, prefix: str = "", design: Path | None = None) -> str:
    rows = (
        f"| {d} | {', '.join(f'`{prefix}{f}`' for f in fs)} |\n" for d, fs in cited(src).items()
    )
    out = HEADER + "".join(rows)
    return out if design is None else out + UNCITED + ", ".join(uncited(src, design)) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(REPO / "src", "src/", REPO / "docs/design.md"), encoding="utf-8")

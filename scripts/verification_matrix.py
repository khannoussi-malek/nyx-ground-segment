"""As-run verification matrix (R25 F4, NPR 7150.2D SWE-052): each M/S requirement in
docs/requirements.md -> each named test -> pass / fail / skipped / missing in THIS run.
Run: python -m scripts.verification_matrix --junit a.xml ... --playwright p.json --out FILE
Exit 1 on drift: a named test absent from the run, or skipped without a reason."""

import argparse
import json
import os
import xml.etree.ElementTree as ET  # noqa: S405 our own CI's pytest output, not external input
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from tests.meta.test_requirements_trace import Ref, evidence

REPO = Path(__file__).resolve().parents[1]
IN_RUN = ("tests/", "e2e/")  # perf/, scripts/, ui/ evidence is not produced by these reporters


@dataclass(frozen=True)
class Case:
    module: str  # junit classname (tests.unit.test_a[.Class]) or playwright file (e2e/x.spec.ts)
    name: str
    status: str  # pass / fail / skipped
    reason: str = ""


def read_junit(path: Path) -> list[Case]:
    out = []
    for tc in ET.parse(path).getroot().iter("testcase"):  # noqa: S314 see import
        sk = tc.find("skipped")
        if sk is not None:
            st, why = "skipped", sk.get("message", "")
        elif tc.find("failure") is not None or tc.find("error") is not None:
            st, why = "fail", ""
        else:
            st, why = "pass", ""
        out.append(Case(tc.get("classname", ""), tc.get("name", ""), st, why))
    return out


def _walk(suite: dict[str, Any]) -> list[Case]:
    out = []
    for spec in suite.get("specs", []):
        f = spec["file"] if spec["file"].startswith("e2e/") else "e2e/" + spec["file"]
        for t in spec["tests"]:
            s = t["status"]
            why = " ".join(a.get("description", "") for a in t.get("annotations", []))
            st = {"skipped": "skipped", "unexpected": "fail"}.get(s, "pass")  # expected, flaky
            out.append(Case(f, spec["title"], st, why.strip()))
    for sub in suite.get("suites", []):
        out += _walk(sub)
    return out


def read_playwright(path: Path) -> list[Case]:
    return _walk(json.loads(path.read_text(encoding="utf-8")))


def _key(path: str) -> str:
    return path[:-3].replace("/", ".") if path.endswith(".py") else path


def status(ref: Ref, cases: list[Case]) -> tuple[str, str]:
    if not ref.path.startswith(IN_RUN):
        return "not in run", ""
    k = _key(ref.path)
    hit = [
        c
        for c in cases
        if (c.module == k or c.module.startswith(k + "."))
        and (ref.name is None or c.name == ref.name or c.name.startswith(ref.name + "["))
    ]
    if not hit:
        return "missing", ""
    if any(c.status == "fail" for c in hit):
        return "fail", ""
    if all(c.status == "skipped" for c in hit):
        why = "; ".join(sorted({c.reason for c in hit}))
        # a skip is allowed only with a reason; a bare skip is drift
        return ("skipped", why) if all(c.reason for c in hit) else ("missing", "")
    return "pass", ""


def render(requirements: str, cases: list[Case], run_id: str, commit: str) -> tuple[str, list[str]]:
    rows, drift, skips = [], [], []
    for rid, refs in evidence(requirements).items():
        for ref in dict.fromkeys(refs):
            label = ref.path + (f"::{ref.name}" if ref.name else "")
            st, why = status(ref, cases)
            rows.append(f"| {rid} | `{label}` | {st} |")
            if st == "missing":
                drift.append(f"{rid}: {label} missing")
            if st == "skipped":
                skips.append(f"- {rid} `{label}`: {why}")
    head = (
        f"# Verification matrix (as run)\n\nrun {run_id}, commit {commit}. Generated by "
        "`scripts/verification_matrix.py` from the CI test results and the evidence named in "
        "`docs/requirements.md` (M and S rows). `missing` = named test absent from the run (CI "
        "fails); `not in run` = perf, script or UI evidence, outside these reporters.\n\n"
        "| Requirement | Named test | Result |\n| --- | --- | --- |\n"
    )
    tail = "\n## Skipped, with reason\n\n" + ("\n".join(skips) or "none") + "\n"
    return head + "\n".join(rows) + "\n" + tail, drift


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--requirements", type=Path, default=REPO / "docs/requirements.md")
    ap.add_argument("--junit", type=Path, nargs="*", default=[])
    ap.add_argument("--playwright", type=Path, nargs="*", default=[])
    ap.add_argument("--out", type=Path, default=Path("verification-matrix.md"))
    a = ap.parse_args(argv)
    cases = [c for p in a.junit for c in read_junit(p)] + [
        c for p in a.playwright for c in read_playwright(p)
    ]
    md, drift = render(
        a.requirements.read_text(encoding="utf-8"),
        cases,
        os.environ.get("GITHUB_RUN_ID", "local"),
        os.environ.get("GITHUB_SHA", "local"),
    )
    a.out.write_text(md, encoding="utf-8")
    for d in drift:
        print("DRIFT", d)
    return 1 if drift else 0


if __name__ == "__main__":
    raise SystemExit(main())
